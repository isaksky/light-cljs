#!/usr/bin/env bash
# Regenerate src/frontend/unicode_ident.rs: the non-ASCII code point ranges of
# the Unicode ID_Start and ID_Continue properties (which already include
# Other_ID_Start and Other_ID_Continue), taken from the Unicode Character
# Database compiled into perl (`\p{ID_Start}`, `\p{ID_Continue}`). The
# generated header records perl's Unicode version.
#
# Usage, from the repository root: scripts/gen-unicode-ident.sh
set -euo pipefail
out=src/frontend/unicode_ident.rs
perl -e '
use strict;
use warnings;
use Unicode::UCD ();
my $version = Unicode::UCD::UnicodeVersion();
sub ranges {
    my ($re) = @_;
    my (@r, $start);
    for my $cp (0x80 .. 0x110000) {
        my $in = $cp <= 0x10FFFF && !($cp >= 0xD800 && $cp <= 0xDFFF) && chr($cp) =~ $re;
        if ($in && !defined $start) { $start = $cp }
        elsif (!$in && defined $start) { push @r, [$start, $cp - 1]; undef $start }
    }
    return @r;
}
sub table {
    my ($name, $doc, @r) = @_;
    my $s = "/// $doc\n#[rustfmt::skip]\npub(super) const $name: &[(u32, u32)] = &[\n";
    while (my @line = splice(@r, 0, 4)) {
        $s .= "   " . join("", map { sprintf(" (0x%05X, 0x%05X),", @$_) } @line) . "\n";
    }
    return $s . "];\n";
}
print "//! Generated by `scripts/gen-unicode-ident.sh` from Unicode $version (the\n";
print "//! Unicode Character Database compiled into perl); do not edit by hand.\n";
print "//!\n";
print "//! Sorted, disjoint, inclusive code point ranges at or above U+0080 of the\n";
print "//! Unicode `ID_Start` and `ID_Continue` properties, which include\n";
print "//! `Other_ID_Start` and `Other_ID_Continue` (UAX #31). ECMAScript adds `\$`\n";
print "//! and `_` to both and ZWNJ and ZWJ to the second (`lexer.rs`).\n\n";
print table("ID_START", "Code points with the `ID_Start` property, U+0080 and above.", ranges(qr/\p{ID_Start}/));
print "\n";
print table("ID_CONTINUE", "Code points with the `ID_Continue` property, U+0080 and above.", ranges(qr/\p{ID_Continue}/));
' > "$out"
echo "wrote $out"
