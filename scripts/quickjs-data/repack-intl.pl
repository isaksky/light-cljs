#!/usr/bin/env perl
use strict;
use warnings;
use File::Path qw(make_path);
use Digest::SHA qw(sha256_hex);

# Repack the verified exporter output, never re-interpret C or string escapes.
# Shared byte pools retain their indices and all embedded/terminal NUL bytes.
my ($input, $out) = @ARGV;
die "usage: repack-intl.pl VERIFIED_EXPORT_DIRECTORY NEW_DATA_DIRECTORY\n"
    unless defined $out && -f "$input/provenance.txt" && !-e $out;
sub read_file {
    open my $f, '<', $_[0] or die "$!";
    local $/; return <$f>;
}
my $source = read_file("$input/tables.rs");
my (%items, @order);
while ($source =~ /(?:#\[derive\(Debug\)\]\n)(pub struct (\w+) \{.*?^\})/msg) {
    $items{$2} = "#[derive(Debug)]\n$1\n"; push @order, $2;
}
while ($source =~ /^(pub static (\w+): .*?;\n)/msg) {
    $items{$2} = "#[rustfmt::skip]\n$1"; push @order, $2;
}
# en-US, pt-BR and zh-Hans-CN have no exact snapshot row: retain their
# parents (pt and zh-Hans are internal fallback data, not extra advertised tags).
my %locales = map { $_ => 1 } qw(en en-GB de fr es ja zh zh-Hant zh-Hans ar ru pt tr zh-TW);
my $rows = $items{locale_data_table} // die "missing locale table";
my @rows = grep { /locale: Some\(b"([^"\\]+)\\x00"\)/ && $locales{$1} }
    split /\n/, $rows;
die "locale subset mismatch\n" unless @rows == keys %locales;
$rows = join("\n", map { s/^.*?(LocaleData \{)/$1/; $_ } @rows);
$items{locale_data_table} = "#[rustfmt::skip]\npub static locale_data_table: &[LocaleData] = &[\n$rows\n];\n";
$items{locale_data_count} = 'pub static locale_data_count: i32 = ' . scalar(@rows) . ";\n";
my %compact = map { $_ => 1 } ($rows =~ /Some\((locale_compact_arr_\d+)\)/g);
my %modules;
for my $name (@order) {
    my $module;
    if ($name =~ /^(?:NumberSymbols|NumberPatterns|CompactDecimalPattern|currency_|locale_currency_|decimal_|group_|plusSign_|minusSign_|percentSign_|infinity_|nan_|pattern_|intl_supported_currenc)/) {
        $module = 'numbers';
    } elsif ($name =~ /^locale_compact_arr_/) {
        next unless $compact{$name}; $module = 'numbers';
    } elsif ($name =~ /^(?:month_|weekday_|era_|ampm_|dayperiod_|date_pattern_|time_pattern_|combined_pattern_)/) {
        $module = 'dates';
    } elsif ($name =~ /^(?:LocaleData|locale_data_)/) {
        $module = 'locale';
    } elsif ($name =~ /^(?:DisplayNamesData|dn_|display_names_)/) {
        $module = 'display_names';
    } elsif ($name =~ /^likely_subtags_/) {
        $module = 'likely_subtags';
    } elsif ($name =~ /^(?:IntlPrefData|IntlWeekData|IntlScriptDir|cal_pref_|time_data_|week_data_|script_dir_)/) {
        $module = 'preferences';
    } else { next; } # Timezone and Unicode integration belong to their consumers.
    $modules{$module} .= $items{$name};
}
make_path($out);
for my $module (sort keys %modules) {
    open my $f, '>', "$out/$module.rs" or die $!;
    print $f "// Generated by scripts/quickjs-data/repack-intl.pl; do not edit.\n",
        "// QuickJS 7d1c13c5d8f8c6b32893786ed35cdcebd88194d2; see provenance.txt.\n",
        "// CLDR-derived data: docs/UNICODE-LICENSE; QuickJS: QUICKJS-LICENSE.\n",
        "#![forbid(unsafe_code)]\n",
        "#![allow(non_upper_case_globals, non_snake_case, clippy::redundant_static_lifetimes)]\n";
    print $f "use super::numbers::*;\n" if $module eq 'locale';
    print $f $modules{$module}; close $f or die $!;
    system('rustfmt', '--edition', '2024', "$out/$module.rs") == 0 or die "rustfmt failed";
}
open my $p, '>', "$out/provenance.txt" or die $!;
print $p read_file("$input/provenance.txt"),
    "Repack: service modules, 14 locale records and referenced compact arrays; shared pools unchanged.\n",
    sha256_hex(read_file($0)), "  scripts/quickjs-data/repack-intl.pl\n";
close $p or die $!;
open my $l, '>', "$out/QUICKJS-LICENSE" or die $!;
print $l read_file("$input/QUICKJS-LICENSE"); close $l or die $!;
