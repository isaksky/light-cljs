#!/usr/bin/env perl
use strict;
use warnings;
use Digest::SHA qw(sha256_hex);
use File::Path qw(make_path);
use Cwd qw(abs_path);

# The snapshot keeps list patterns in code, not locale-data.c. Compile only
# its separator selector as an offline exporter; no JS engine is linked.
my ($import, $source, $out) = @ARGV;
die "usage: repack-lists.pl VERIFIED_IMPORT QUICKJS_SOURCE NEW_OUTPUT\n"
    unless @ARGV == 3 && !-e $out;
$source = abs_path($source);
sub read_file {
    open my $f, '<', $_[0] or die $!;
    local $/; return <$f>;
}
sub write_file {
    open my $f, '>', $_[0] or die $!;
    print $f $_[1]; close $f or die $!;
}
my $pin = '974db3d3425c074968de1b93acf2b9113a910460be5de24bd106831a9ff3d8dd';
my $code = read_file("$source/intl/listformat.c");
die "unpinned intl/listformat.c\n" unless sha256_hex($code) eq $pin;
my $provenance = read_file("$import/provenance.txt");
die "unverified import\n" unless $provenance =~ /Validation: all exported logical values match/;
my ($record) = $code =~ /(^typedef struct \{[^{}]+\} JSListFormatData;)/ms;
die "missing ListFormat record\n" unless defined $record;
my $functions = '';
for my $name (qw(is_locale_spanish is_locale_british js_listformat_get_separators)) {
    my ($function) = $code =~ /(^static [^\n]*\b\Q$name\E\(.*?^\})/ms;
    die "missing $name\n" unless defined $function;
    $functions .= "$function\n";
}
my @locales = qw(en en-US en-GB de fr es ja zh zh-Hant zh-Hans-CN ar ru pt-BR tr zh-TW);
make_path($out);
my $export = <<'C';
/* Offline data export. QuickJS MIT notice: QUICKJS-LICENSE. */
#include <stdio.h>
#include <string.h>
typedef void JSContext;
static int strstart(const char *s, const char *prefix, const char **rest) {
    size_t n = strlen(prefix);
    if (strncmp(s, prefix, n)) return 0;
    if (rest) *rest = s + n;
    return 1;
}
C
$export .= $record . "\n" . $functions . "\nint main(void) {\n";
$export .= 'const char *locales[] = {' . join(',', map { qq("$_") } @locales) . "};\n";
$export .= <<'C';
const char *types[] = {"conjunction", "disjunction", "unit"};
const char *styles[] = {"long", "short", "narrow"};
for (int l = 0; l < 15; l++) for (int t = 0; t < 3; t++) for (int s = 0; s < 3; s++) {
    JSListFormatData data = {(char *)locales[l], (char *)types[t], (char *)styles[s]};
    const char *separators[4];
    if (js_listformat_get_separators(NULL, &data, &separators[0], &separators[1], &separators[2], &separators[3])) return 1;
    for (int p = 0; p < 4; p++) {
        printf("%s %d %d %d ", locales[l], t, s, p);
        for (const unsigned char *c = (const unsigned char *)separators[p]; *c; c++) printf("%02x", *c);
        puts("");
    }
}
return ferror(stdout) ? 1 : 0;
}
C
write_file("$out/export.c", $export);
system($ENV{CC} // 'cc', '-std=c11', '-O0', "$out/export.c", '-o', "$out/export") == 0 or die "compile lists\n";
open my $pipe, '-|', "$out/export" or die $!;
my (@patterns, $reference);
while (<$pipe>) {
    $reference .= $_;
    /^(\S+) ([0-2]) ([0-2]) ([0-3]) ([0-9a-f]*)\n$/ or die "invalid pattern\n";
    my ($locale, $type, $style, $part, $hex) = ($1, $2, $3, $4, $5);
    my $index = @patterns;
    die "pattern order\n" unless $locale eq $locales[int($index / 36)] && $index % 36 == $type * 12 + $style * 4 + $part;
    # Rust ASCII escapes preserve exactly the C bytes; no string parsing.
    $hex =~ s/(..)/\\x$1/g;
    push @patterns, qq("$hex");
}
close $pipe or die "list export failed\n";
die "pattern count\n" unless @patterns == 540;
my $rust = "// Generated by scripts/quickjs-data/repack-lists.pl; do not edit.\n" .
    "// QuickJS 7d1c13c5d8f8c6b32893786ed35cdcebd88194d2; list_provenance.txt.\n" .
    "// QuickJS MIT: QUICKJS-LICENSE; Unicode notice: docs/UNICODE-LICENSE.\n" .
    "#![forbid(unsafe_code)]\n";
$rust .= 'pub static LOCALES: &[&str] = &[' . join(',', map { qq("$_") } @locales) . "];\n";
$rust .= 'pub static SEPARATORS: &[&str] = &[' . join(',', @patterns) . "];\n";
write_file("$out/lists.rs", $rust);
system('rustfmt', '--edition', '2024', "$out/lists.rs") == 0 or die "rustfmt lists\n";
write_file("$out/reference.txt", $reference);
write_file("$out/verify.rs", <<'R');
#![forbid(unsafe_code)]
mod lists;
fn main() {
    let path = std::env::args().nth(1).unwrap();
    let reference = std::fs::read_to_string(path).unwrap();
    let mut actual = String::new();
    for (l, locale) in lists::LOCALES.iter().enumerate() {
        for t in 0..3 { for s in 0..3 { for p in 0..4 {
            use std::fmt::Write;
            write!(actual, "{locale} {t} {s} {p} ").unwrap();
            for byte in lists::SEPARATORS[l * 36 + t * 12 + s * 4 + p].bytes() {
                write!(actual, "{byte:02x}").unwrap();
            }
            actual.push('\n');
        } } }
    }
    assert_eq!(lists::SEPARATORS.len(), lists::LOCALES.len() * 36);
    assert_eq!(actual, reference);
    println!("PASS: all 540 list separators match the pinned C selector");
}
R
write_file("$out/provenance.txt", $provenance .
    "ListFormat: all type/style/start/middle/end/pair selectors for 15 test locales.\n" .
    "$pin  intl/listformat.c\n" . sha256_hex(read_file($0)) . "  scripts/quickjs-data/repack-lists.pl\n");
write_file("$out/QUICKJS-LICENSE", read_file("$import/QUICKJS-LICENSE"));
