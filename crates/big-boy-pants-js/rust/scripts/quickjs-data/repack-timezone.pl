#!/usr/bin/env perl
use strict;
use warnings;
use File::Path qw(make_path);
use Digest::SHA qw(sha256_hex);
my ($input, $out) = @ARGV;
die "usage: repack-timezone.pl VERIFIED_EXPORT_DIRECTORY NEW_DATA_DIRECTORY\n"
    unless defined $out && -f "$input/provenance.txt" && !-e $out;
sub read_file { open my $f, '<', $_[0] or die $!; local $/; return <$f>; }
my $source = read_file("$input/tables.rs");
my @items;
while ($source =~ /(?:#\[derive\(Debug\)\]\n)(pub struct (?:TZTransition|TZData|TZAlias|TiTzRegion) \{.*?^\})/msg) {
    push @items, "#[derive(Debug)]\n$1\n";
}
while ($source =~ /^(pub static (?:ti_tz_\w+|tz_trans_\w+): .*?;\n)/msg) {
    push @items, "#[rustfmt::skip]\n$1";
}
die "missing timezone types/tables\n" unless @items > 10;
make_path($out);
open my $f, '>', "$out/tables.rs" or die $!;
print $f "// Generated by scripts/quickjs-data/repack-timezone.pl; do not edit.\n",
    "// QuickJS 7d1c13c5d8f8c6b32893786ed35cdcebd88194d2; see provenance.txt.\n",
    "// QuickJS license: QUICKJS-LICENSE; data notice: docs/UNICODE-LICENSE.\n",
    "#![forbid(unsafe_code)]\n",
    "#![allow(dead_code, non_upper_case_globals, clippy::redundant_static_lifetimes)]\n", @items;
close $f or die $!;
system('rustfmt', '--edition', '2024', "$out/tables.rs") == 0 or die "rustfmt failed";
open my $p, '>', "$out/provenance.txt" or die $!;
print $p read_file("$input/provenance.txt"), "Repack: timezone types and tables unchanged.\n",
    sha256_hex(read_file($0)), "  scripts/quickjs-data/repack-timezone.pl\n";
close $p or die $!;
open my $l, '>', "$out/QUICKJS-LICENSE" or die $!;
print $l read_file("$input/QUICKJS-LICENSE"); close $l or die $!;
