// BMP decimal digits from tools.reader's Character.isDigit(char), as captured
// by tests/reference/reader_classes.clj. Supplementary scalars are not digits
// for that UTF-16-char API. Keep the ASCII path in the byte scanner.
pub(crate) fn unicode_digit(ch: char) -> bool {
    matches!(ch as u32,
        0x0660..=0x0669
        | 0x06f0..=0x06f9
        | 0x07c0..=0x07c9
        | 0x0966..=0x096f
        | 0x09e6..=0x09ef
        | 0x0a66..=0x0a6f
        | 0x0ae6..=0x0aef
        | 0x0b66..=0x0b6f
        | 0x0be6..=0x0bef
        | 0x0c66..=0x0c6f
        | 0x0ce6..=0x0cef
        | 0x0d66..=0x0d6f
        | 0x0de6..=0x0def
        | 0x0e50..=0x0e59
        | 0x0ed0..=0x0ed9
        | 0x0f20..=0x0f29
        | 0x1040..=0x1049
        | 0x1090..=0x1099
        | 0x17e0..=0x17e9
        | 0x1810..=0x1819
        | 0x1946..=0x194f
        | 0x19d0..=0x19d9
        | 0x1a80..=0x1a89
        | 0x1a90..=0x1a99
        | 0x1b50..=0x1b59
        | 0x1bb0..=0x1bb9
        | 0x1c40..=0x1c49
        | 0x1c50..=0x1c59
        | 0xa620..=0xa629
        | 0xa8d0..=0xa8d9
        | 0xa900..=0xa909
        | 0xa9d0..=0xa9d9
        | 0xa9f0..=0xa9f9
        | 0xaa50..=0xaa59
        | 0xabf0..=0xabf9
        | 0xff10..=0xff19)
}
